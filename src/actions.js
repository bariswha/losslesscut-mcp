export const BLOCKED_ACTIONS = new Set([
  'quit',
  'cleanupFilesDialog',
  'openSendReportDialog',
  'openFiles',
  'goToTimecodeDirect',
  'importEdlFile',
  'exportEdlFile',
  'promptDownloadMediaUrl',
]);

export const ACTION_GROUP_BY_NAME = new Map(
  Object.entries(ACTION_GROUPS).flatMap(([group, names]) => names.map((name) => [name, group])),
);

export const ALLOWED_ACTIONS = new Set(ACTION_GROUP_BY_NAME.keys());

export function isAllowedAction(name) {
  return typeof name === 'string' && ALLOWED_ACTIONS.has(name) && !BLOCKED_ACTIONS.has(name);
}
